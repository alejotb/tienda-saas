  Future<void> _handleLogin() async {
    if (_model.emailAddressTextController.text.trim().isEmpty ||
        _model.passwordTextController.text.trim().isEmpty) {
      return;
    }
    GoRouter.of(context).prepareAuthEvent();

    final user = await authManager.signInWithEmail(
      context,
      _model.emailAddressTextController.text.trim(),
      _model.passwordTextController.text,
    );
    if (user == null) {
      AppStateNotifier.instance.updateNotifyOnAuthChange(true);
      return;
    }

    AppStateNotifier.instance.updateNotifyOnAuthChange(true);
    AppStateNotifier.instance.stopShowingSplashImage();

    if (context.mounted) {
      if (widget.fromPage != null && widget.fromPage!.startsWith('/')) {
        context.go(widget.fromPage!);
      } else {
        context.goNamedAuth(
            widget.fromPage ?? MainHomePageWidget.routeName,
            context.mounted);
      }
    }
  }

